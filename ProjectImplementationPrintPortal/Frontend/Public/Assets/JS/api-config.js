/* Public site addresses only — never put tokens, passwords or connection strings here.
 * The generated JSON is available to the browser on BOTH hosting providers.
 * dev.env is local-only; GitHub Actions supplies the same PUBLIC_* keys via vars.
 */
const DEFAULTS = Object.freeze({
  cloudflareSite: 'https://cloudcomputing-printportal.pages.dev',
  cloudflareApi: 'https://printportal-worker.rikerhoch.workers.dev',
  azureSite: 'https://wellingtionprint-dxhudcabe8hdhmee.japaneast-01.azurewebsites.net',
  azureClassSite: '', // Optional second Azure account / classmate deployment.
  deploymentMode: 'auto', // Generated by CI to pin each app to its own API.
});

export const API_LABELS = Object.freeze({
  cloud: 'Cloudflare Worker',
  azure: 'Azure App Service',
  'azure-class': 'Azure · class deployment',
  local: 'Local Express',
});

let publicConfig = { ...DEFAULTS };

function parseOrigin(input) {
  if (typeof input !== 'string' || !input.trim()) return '';
  try {
    const url = new URL(input);
    const local = ['localhost', '127.0.0.1', '[::1]'].includes(url.hostname);
    if ((url.protocol !== 'https:' && !(local && url.protocol === 'http:')) ||
        url.username || url.password || url.pathname !== '/' || url.search || url.hash) return '';
    return url.origin;
  } catch {
    return '';
  }
}

// Load per-deployment public settings; a missing file falls back to known demo URLs.
export async function loadPublicConfig(fetchImpl = fetch) {
  try {
    const response = await fetchImpl('./Assets/JSON/public-config.json', { cache: 'no-store' });
    if (response.ok) {
      const data = await response.json();
      const valid = {};
      for (const key of Object.keys(DEFAULTS)) {
        if (Object.hasOwn(data, key)) {
          valid[key] = key === 'deploymentMode' && ['auto', 'cloud', 'azure', 'azure-class'].includes(data[key])
            ? data[key] : key === 'deploymentMode' ? 'auto' : parseOrigin(data[key]);
        }
      }
      publicConfig = { ...DEFAULTS, ...valid };
    }
  } catch {
    // Offline previews still work with the bundled public defaults.
  }
  return getPublicConfig();
}

export function getPublicConfig() {
  return { ...publicConfig };
}

export function defaultApiMode(hostname) {
  if (['localhost', '127.0.0.1', '[::1]'].includes(hostname)) return 'local';
  // Host or build target is authoritative: localStorage is separate on every domain.
  if (publicConfig.deploymentMode !== 'auto' && canUseMode(publicConfig.deploymentMode, hostname))
    return publicConfig.deploymentMode;
  if (publicConfig.azureClassSite && new URL(publicConfig.azureClassSite).hostname === hostname) return 'azure-class';
  if (publicConfig.azureSite && new URL(publicConfig.azureSite).hostname === hostname) return 'azure';
  return 'cloud';
}

export function canUseMode(mode, hostname) {
  if (mode === 'cloud') return Boolean(publicConfig.cloudflareSite && publicConfig.cloudflareApi);
  if (mode === 'azure') return Boolean(publicConfig.azureSite);
  if (mode === 'azure-class') return Boolean(publicConfig.azureClassSite);
  // Never redirect a remote visitor to their own localhost server.
  if (mode === 'local') return ['localhost', '127.0.0.1', '[::1]'].includes(hostname);
  return false;
}

export function apiOriginFor(mode, currentOrigin = '') {
  if (mode === 'cloud') return publicConfig.cloudflareApi;
  if (mode === 'azure' || mode === 'azure-class') {
    const configured = mode === 'azure' ? publicConfig.azureSite : publicConfig.azureClassSite;
    // Once on Azure, prefer its own /api to avoid cross-origin requests.
    if (currentOrigin && (publicConfig.deploymentMode === mode || currentOrigin === configured))
      return currentOrigin;
    return configured;
  }
  if (mode === 'local') {
    try {
      const url = new URL(currentOrigin);
      if (['localhost', '127.0.0.1', '[::1]'].includes(url.hostname)) return `${url.protocol}//${url.hostname}:3000`;
    } catch { /* Unknown local origin. */ }
    return 'http://localhost:3000';
  }
  return '';
}

// Move to the OTHER website, not a cross-origin API call. Retain page and filters.
export function navigationTarget(mode, currentUrl) {
  const page = new URL(currentUrl);
  if (!canUseMode(mode, page.hostname)) return '';
  const site = mode === 'cloud' ? publicConfig.cloudflareSite
    : mode === 'azure' ? publicConfig.azureSite
    : mode === 'azure-class' ? publicConfig.azureClassSite
    : `${page.protocol}//${page.hostname}:3000`;
  const next = new URL(site);
  const leaf = page.pathname.split('/').filter(Boolean).pop();
  next.pathname = leaf === 'requestSubmission.html' ? '/requestSubmission.html' : '/index.html';
  next.search = page.search;
  return next.href;
}
